"""Benchmark of the production rule integration — no model, no cost: what the ENGINE side does with production knowledge, on drawings whose
truth is known (generated by plan_bench's box generator, so every size, line and the intended result after a change are known exactly).

It measures the parts a model's reading cannot hide:

  binding      a binding the generator's truth gives (inputs = the drawing's sizes, outputs = its overall dimensions) holds by the production
               code; every deliberately corrupted binding (a wrong count stated, a wrong size or wrong lines bound, a level bound to a length, a
               number for a reference, a field whose unit is unknown) is caught — differs or refused. A corrupted binding that HOLDS is a false
               acceptance: the benchmark fails on any.
  guards       a correct change on views drawn in projection is applied and the production relation still holds; the same change when the other
               view is a unit of its own (it does not follow) is refused, and the sheet is exactly as before
  validation   (a family whose engine validates) a change the engine's own check rejects on the drawing's values is refused; one it accepts is applied
  topology     a change of count is classified as a topology change and not applied; a value change names the drawing value that drives it
  discovery    the families a drawing's printed words point at, where the drawing names its kind of structure

What it does not measure: how well a MODEL chooses bindings, families and plans — that is the live agent run's job (agent-eval --live).

    dxf-autoparam production bench          # a table and production_bench.json
"""

from __future__ import annotations

import copy
import json
import random
import tempfile
import time
from dataclasses import replace
from pathlib import Path

from ..crossview import SheetError, SheetModel
from ..plan_bench import Box, box_answer, box_gad, faces
from . import manifest as M
from .bridge import default_bridge

PLAN_INSTRUCTION = "Reduce the clear span to {v} mm. Maintain the outer wall thickness. Keep the foundation fixed. Keep the cells centred about the centre line."
PLAN_DECISIONS = {"attached:WingLeft": "follow", "attached:WingRight": "follow", "attached:PitchingDetail": "keep_fixed"}


def _sheet(b: Box, workdir: Path, name: str, unlink: bool = False) -> tuple[SheetModel, str, str, dict]:
    g = box_gad(workdir / f"{name}.dxf", b)
    sm = SheetModel.open(g["path"])
    two = next(k for k, u in sm.units.items() if len(u.views) == 2)
    va, vb = sm.units[two].views
    if unlink:
        sm.link(va, vb, False)
    sec = max((va, vb), key=lambda v: sm.layout.group(v).bbox[3])
    pln = vb if sec == va else va
    us, up = sm.unit_of_view[sec], sm.unit_of_view[pln]
    sm.commit_answer(us, box_answer(sm, us, g["box"], g["handles"]))
    return sm, us, up, g


def _line(sm: SheetModel, uid: str, axis: str, at: float) -> str:
    u = sm.unit(uid)
    return min((d for d in u.an.datums.values() if d.axis == axis), key=lambda d: abs(d.value * u.sub.units_mm - at)).id


def truth_binding(sm: SheetModel, us: str, b: Box, family: str = "railway_rcc_box", plan_unit: str | None = None) -> dict:
    """The binding the generator's truth gives: the drawing's sizes as inputs, its overall dimensions and levels as outputs."""
    f = faces(b)
    inputs = {"geometry.clear_w": "ClearSpan", "geometry.t_wall_o": "OuterWall", "geometry.t_slab_t": "TopSlab", "geometry.t_slab_b": "BottomSlab",
              "geometry.clear_h": {"lines": [_line(sm, us, "y", b.bottom), _line(sm, us, "y", b.bottom + b.height)]}}
    if b.cells > 1:
        inputs["geometry.t_wall_i"] = {"lines": [_line(sm, us, "x", f[2]), _line(sm, us, "x", f[3])]}
    total_w = {"lines": [_line(sm, us, "x", 0.0), _line(sm, us, "x", b.width)]}
    if plan_unit and plan_unit != us:
        total_w = {"unit": plan_unit, "lines": [_line(sm, plan_unit, "x", 0.0), _line(sm, plan_unit, "x", b.width)]}
    return {"family": family, "unit": us, "inputs": inputs, "config": {"project.cells": {"value": b.cells, "basis": f"{b.cells} cell(s) drawn"}},
            "outputs": {"total_w": total_w, "total_h": {"lines": [_line(sm, us, "y", 0.0), _line(sm, us, "y", b.bottom + b.height + b.top)]}}}


def corruptions(sm: SheetModel, us: str, b: Box, good: dict, fam: M.FamilyKnowledge) -> list[tuple[str, dict]]:
    out = []
    c = copy.deepcopy(good)
    c["config"]["project.cells"]["value"] = b.cells + 1
    out.append(("wrong count stated", c))
    if abs(b.top - b.wall) > 2:
        c = copy.deepcopy(good)
        c["inputs"]["geometry.t_wall_o"] = "TopSlab"
        out.append(("a size bound to the wrong value", c))
    c = copy.deepcopy(good)
    f = faces(b)
    c["outputs"]["total_w"] = {"lines": [_line(sm, us, "x", f[1]), _line(sm, us, "x", f[2])]}
    out.append(("an output bound to the wrong lines", c))
    c = copy.deepcopy(good)
    c["inputs"]["hydraulics.bed_lvl"] = "ClearSpan"
    out.append(("a level bound to a length", c))
    c = copy.deepcopy(good)
    c["inputs"]["geometry.clear_w"] = 3000
    out.append(("a number in place of a reference", c))
    unknown = next((p for p, r in fam.params.items() if r.get("unit") == "unknown" and r.get("type") == "number"), None)
    if unknown:
        c = copy.deepcopy(good)
        c["inputs"][unknown] = "OuterWall"
        out.append((f"a field whose unit is unknown ({unknown})", c))
    c = copy.deepcopy(good)
    c["inputs"]["geometry.no_such_field"] = "OuterWall"
    out.append(("a field the family does not have", c))
    return out


def _evaluate(sm: SheetModel, binding: dict) -> dict:
    from .service import ProductionRefusal, report

    try:
        return report(binding, sm._domain_state(binding))
    except ProductionRefusal as exc:
        return {"status": "refused", "problems": [str(exc)]}


def run(n: int = 24, seed: int = 5, out_path: str | None = None, workdir: Path | None = None) -> dict:
    t0 = time.perf_counter()
    work = Path(workdir or tempfile.mkdtemp(prefix="production-bench-"))
    st = default_bridge().status()
    rep: dict = {"bridge": {"available": st["available"], **({"why": st.get("reason")} if not st["available"] else {})}, "cases": []}
    if not st["available"]:
        rep["summary"] = {"false_acceptances": 0, "skipped": "the production rule bridge cannot run here: nothing was measured"}
        return rep
    pk = M.knowledge()
    fam = pk.family("railway_rcc_box")
    rng = random.Random(seed)
    holds = rel = detected = corrupted = false_acc = unjudged = 0
    by_kind: dict[str, list[int]] = {}  # kind → [caught, not judged, total]
    for k in range(n):
        b = Box(cells=1 + k % 4, span=float(rng.randrange(1500, 5000, 50)), height=float(rng.randrange(1500, 4000, 50)),
                wall=float(rng.randrange(250, 500, 25)), mid=float(rng.randrange(200, 450, 25)), top=float(rng.randrange(250, 500, 25)),
                bottom=float(rng.randrange(250, 500, 25)), plan=True, detail=False)
        sm, us, _up, _g = _sheet(b, work, f"b{k}")
        good = truth_binding(sm, us, b)
        r = _evaluate(sm, good)
        outs = r.get("outputs") or {}
        h = sum(1 for o in outs.values() if o["result"] == "holds")
        holds += h
        rel += len(good["outputs"])
        case = {"id": f"B{k:02d}", "box": {"cells": b.cells, "span": b.span, "height": b.height, "wall": b.wall, "mid": b.mid, "top": b.top, "bottom": b.bottom},
                "truth": {o: v["result"] for o, v in outs.items()}, "corrupted": []}
        for kind, cb in corruptions(sm, us, b, good, fam):
            rr = _evaluate(sm, cb)
            caught = rr.get("status") in ("refused", "differs")
            judged = caught or rr.get("status") == "holds"
            corrupted += 1
            detected += caught
            unjudged += not judged
            if rr.get("status") == "holds":
                false_acc += 1
            row = by_kind.setdefault(kind.split(" (")[0], [0, 0, 0])
            row[0] += caught
            row[1] += not judged
            row[2] += 1
            case["corrupted"].append({"kind": kind, "status": rr.get("status"), "caught": caught,
                                      **({"waits_for": sorted({w for o in (rr.get("outputs") or {}).values() for w in o.get("waits_for", [])})[:6]}
                                         if not judged else {})})
        rep["cases"].append(case)
    # guards: the same plan on views drawn in projection (follows) and on a view that is a unit of its own (does not)
    guards = []
    for unlink in (False, True):
        for k, b in enumerate((Box(), Box(cells=3, span=2500.0, mid=250.0), Box(cells=1, span=3200.0))):
            b = replace(b, detail=True)
            sm, us, up, _g = _sheet(b, work, f"g{int(unlink)}{k}", unlink=unlink)
            sm.bind_domain(truth_binding(sm, us, b, plan_unit=up))
            before = copy.deepcopy(sm._state())
            rev = sm.revision
            want = b.span - 500.0
            try:
                res = sm.apply_plan(us, {"instruction": PLAN_INSTRUCTION.format(v=f"{want:g}"), "decisions": PLAN_DECISIONS})
                final = sm.domain_report()
                guards.append({"linked": not unlink, "cells": b.cells, "outcome": "applied", "views_changed": sorted(v for v, c in res["applied"]["by_view"].items() if c),
                               "relation_after": final[0]["outputs"]["total_w"]["result"], "correct": not unlink})
            except SheetError as exc:
                after = sm._state()
                untouched = (after["values"] == before["values"] and after["answers"] == before["answers"] and after["domain"] == before["domain"]
                             and sm.revision == rev)
                guards.append({"linked": not unlink, "cells": b.cells, "outcome": "refused", "why": str(exc)[:220], "state_untouched": untouched,
                               "correct": unlink and untouched and "production rule" in str(exc)})
    rep["guards"] = guards
    # validation: a family whose engine validates, a change its own check rejects (decided by the drawing's values) and one it accepts
    val = []
    if pk.family("highway_rcc_box").data["capabilities"].get("has_validate"):
        for value, expect in ((250.0, "refused"), (400.0, "applied")):
            b = replace(Box(), detail=False)
            sm, us, _up, _g = _sheet(b, work, f"v{int(value)}")
            vb = truth_binding(sm, us, b, family="highway_rcc_box")
            vb["config"] = {"project.cells": {"value": b.cells, "basis": "drawn"}}
            acc = sm.bind_domain(vb)
            before = copy.deepcopy(sm._state())
            r = sm.apply({f"{us}.OuterWall": value})
            outcome = "applied" if r.ok else "refused"
            untouched = sm._state()["values"] == before["values"] if not r.ok else None
            val.append({"change": f"OuterWall = {value:g} mm", "outcome": outcome, "expected": expect, "guard_validation": acc.get("guard_validation"),
                        "why": next((e for e in r.errors if "validation" in e), "")[:200], "state_untouched": untouched, "correct": outcome == expect})
    rep["validation"] = val
    # topology vs value: what assess_change classifies
    from ..ai.production import ProductionSession

    b = Box()
    sm, us, _up, _g = _sheet(b, work, "t")
    sm.bind_domain(truth_binding(sm, us, b))

    class _Bench:  # the parts of a run's bench assess_change reads
        def __init__(self, sm):
            self.sm, self.units, self.active = sm, {}, us
            self.run = type("R", (), {"scope": {"units": [us]}})()

        @staticmethod
        def _lock():
            import contextlib

            return contextlib.nullcontext()

    ses = ProductionSession(pk, _Bench(sm))
    topo = ses._assess_change({"project.cells": b.cells + 1}, family="railway_rcc_box")
    value = ses._assess_change({"geometry.clear_w": 2.5}, family="railway_rcc_box")
    rep["topology"] = {
        "count_change": {"status": topo["fields"][0].get("status"), "can_apply": topo["fields"][0].get("can_apply"),
                         "total_w": topo.get("outputs", {}).get("total_w"), "correct": topo["fields"][0].get("status") == "topology_change"},
        "value_change": {"status": value["fields"][0].get("status"), "drives": value["fields"][0].get("drives"),
                         "requested_value": value["fields"][0].get("requested_value"),
                         "correct": value["fields"][0].get("drives") == "ClearSpan" and abs((value["fields"][0].get("requested_value") or 0) - 2500.0) < 1e-6}}
    # discovery: generated sheets print "<n> CELL RCC BOX …" — either box family is right; the two must be reported as a close call
    from ..ai.library import drawing_texts

    found = pk.discover(drawing_texts(sm.dr.items))
    top2 = [f["family"] for f in found[:2]]
    rep["discovery"] = {"drawing_says": next((t for t in drawing_texts(sm.dr.items) if "BOX" in t.upper()), ""), "found": found[:3],
                        "correct": bool(top2) and set(top2) <= {"railway_rcc_box", "highway_rcc_box"} and top2[0] in {"railway_rcc_box", "highway_rcc_box"}}
    g_ok = sum(1 for g in guards if g["correct"])
    rep["summary"] = {
        "binding_truth_holds": f"{holds}/{rel}", "binding_truth_rate": round(holds / max(1, rel), 4),
        "corruptions_caught": f"{detected}/{corrupted}", "corruption_detection_rate": round(detected / max(1, corrupted), 4),
        "corruptions_not_judged": f"{unjudged}/{corrupted}",
        "false_acceptances": false_acc + sum(1 for g in guards if g["outcome"] == "applied" and not g["linked"])
        + sum(1 for v in val if v["outcome"] == "applied" and v["expected"] == "refused"),
        "by_corruption": {k: f"{a}/{t} caught" + (f", {u} not judged (waits for an unbound field)" if u else "") for k, (a, u, t) in by_kind.items()},
        "guards_correct": f"{g_ok}/{len(guards)}", "refusals_left_state_untouched": all(g.get("state_untouched", True) for g in guards if g["outcome"] == "refused"),
        "validation_correct": f"{sum(1 for v in val if v['correct'])}/{len(val)}",
        "topology_classified": rep["topology"]["count_change"]["correct"] and rep["topology"]["value_change"]["correct"],
        "discovery_correct": rep["discovery"]["correct"], "seconds": round(time.perf_counter() - t0, 1)}
    if out_path:
        Path(out_path).write_text(json.dumps(rep, indent=1, default=str))
    return rep


def table(rep: dict) -> str:
    s = rep.get("summary", {})
    if s.get("skipped"):
        return f"production bench skipped: {s['skipped']}"
    rows = [("correct bindings hold (production code)", s["binding_truth_holds"]),
            ("corrupted bindings caught (differs / refused)", s["corruptions_caught"]),
            ("corrupted bindings not judged (never accepted)", s["corruptions_not_judged"]),
            *[(f"  · {k}", v) for k, v in s["by_corruption"].items()],
            ("FALSE ACCEPTANCES", str(s["false_acceptances"])),
            ("guards: linked applied / unlinked refused", s["guards_correct"]),
            ("refusals left the sheet untouched", str(s["refusals_left_state_untouched"])),
            ("validation guard (refuse / accept)", s["validation_correct"]),
            ("count change classified as topology; value change planned", str(s["topology_classified"])),
            ("family discovery from printed words", str(s["discovery_correct"])),
            ("seconds", str(s["seconds"]))]
    w = max(len(r[0]) for r in rows)
    return "\n".join(f"{a:<{w}}  {b}" for a, b in rows)
