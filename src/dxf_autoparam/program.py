"""The parametric program — the UPCE shape, in plain data:

    PARAMETERS   named values a person types (Width = 3000 mm, GroundLevel = 96.100 m)
        ↓
    FORMULAS     every set-out line (datum) as an expression of parameters and other datums
                 ("x7 = x3 + Width"), plus named derived values ("TotalWidth = …")
        ↓
    BINDINGS     every entity point = its datum + a fixed offset (from the analysis)
        ↓
    GEOMETRY     regenerated by evaluating the formulas in dependency order

All lengths in formulas are millimetres; levels are metres (a level line's formula is
"FormationLevel * 1000"). Expressions are a small safe language, checked as a syntax tree before anything is
evaluated (no Python is ever executed beyond these operations on numbers):

  arithmetic    + − × ÷ ** (or ^), parentheses, unary minus
  functions     min max abs sqrt round floor ceil sign hypot clamp(x, lo, hi)
  angles        sind cosd tand  (argument in DEGREES)       asind acosd atand atan2d(y, x)  (result in degrees)
                sin cos tan     (argument in RADIANS)       asin acos atan atan2(y, x)      (result in radians)
                deg(r) rad(d)   conversions; pi
  vectors       hypot(dx, dy) · dot(ax, ay, bx, by) · cross(ax, ay, bx, by)
                rotx(px, py, cx, cy, a) / roty(…): a point rotated about (cx, cy) by a degrees (x / y of the result)
  conditions    a if c else b, with < <= > >= == != and / or / not (true = 1, false = 0)

A domain error (sqrt of a negative, asin beyond ±1), a division by zero, or a result that is not a finite number is
refused with the reason (ExprError), never turned into a coordinate. `check_dims` refuses a formula that mixes kinds of
quantity (a length plus an angle, a sine of a length, a set-out line that is not a length).
"""

