def _sign(x: float) -> float:
    return (x > 0) - (x < 0)


def _clamp(x: float, lo: float, hi: float) -> float:
    if lo > hi:
        raise ValueError("clamp: the lower bound is above the upper bound")
    return min(max(x, lo), hi)


def _rotx(px: float, py: float, cx: float, cy: float, a: float) -> float:
    r = math.radians(a)
    return cx + (px - cx) * math.cos(r) - (py - cy) * math.sin(r)


def _roty(px: float, py: float, cx: float, cy: float, a: float) -> float:
    r = math.radians(a)
    return cy + (px - cx) * math.sin(r) + (py - cy) * math.cos(r)


FUNCS = {
    "min": min, "max": max, "abs": abs, "sqrt": math.sqrt, "round": round, "floor": math.floor, "ceil": math.ceil,
    "sign": _sign, "hypot": math.hypot, "clamp": _clamp,
    # degrees (drafting): the name says the unit
    "sind": lambda a: math.sin(math.radians(a)), "cosd": lambda a: math.cos(math.radians(a)), "tand": lambda a: math.tan(math.radians(a)),
    "asind": lambda v: math.degrees(math.asin(v)), "acosd": lambda v: math.degrees(math.acos(v)), "atand": lambda v: math.degrees(math.atan(v)),
    "atan2d": lambda y, x: math.degrees(math.atan2(y, x)),
    # radians (mathematics)
    "sin": math.sin, "cos": math.cos, "tan": math.tan, "asin": math.asin, "acos": math.acos, "atan": math.atan, "atan2": math.atan2,
    "deg": math.degrees, "rad": math.radians,
    # vectors in components
    "dot": lambda ax, ay, bx, by: ax * bx + ay * by, "cross": lambda ax, ay, bx, by: ax * by - ay * bx,
    "rotx": _rotx, "roty": _roty,
}
ARITY = {"clamp": 3, "hypot": 2, "atan2d": 2, "atan2": 2, "dot": 4, "cross": 4, "rotx": 5, "roty": 5,
         **{f: 1 for f in ("abs", "sqrt", "floor", "ceil", "sign", "sind", "cosd", "tand", "asind", "acosd", "atand",
                           "sin", "cos", "tan", "asin", "acos", "atan", "deg", "rad")}}
CONSTS = {"pi": math.pi}
_NODES = (ast.Expression, ast.BinOp, ast.UnaryOp, ast.Constant, ast.Name, ast.Load, ast.Call, ast.Add, ast.Sub, ast.Mult, ast.Div,
          ast.Pow, ast.USub, ast.UAdd, ast.Compare, ast.Lt, ast.LtE, ast.Gt, ast.GtE, ast.Eq, ast.NotEq, ast.IfExp, ast.BoolOp,
          ast.And, ast.Or, ast.Not)


class ExprError(ValueError):
    pass


@lru_cache(maxsize=1 << 17)  # a big sheet re-evaluates ~10k formulas per regeneration; the trees are never mutated
def parse(expr: str) -> ast.Expression:
    try:
        tree = ast.parse(expr.replace("^", "**"), mode="eval")
    except SyntaxError as exc:
        raise ExprError(f"not an expression: {expr!r}") from exc
    for node in ast.walk(tree):
        if not isinstance(node, _NODES):
            raise ExprError(f"{type(node).__name__} is not allowed in {expr!r}")
        if isinstance(node, ast.Constant) and (not isinstance(node.value, (int, float)) or isinstance(node.value, bool)):
            raise ExprError(f"only numbers are allowed as constants in {expr!r}")
        if isinstance(node, ast.Call):
            if not (isinstance(node.func, ast.Name) and node.func.id in FUNCS) or node.keywords:
                raise ExprError(f"unknown function in {expr!r}")
            want = ARITY.get(node.func.id)
            if want is not None and len(node.args) != want:
                raise ExprError(f"{node.func.id} takes {want} argument(s), not {len(node.args)}, in {expr!r}")
            if node.func.id in ("min", "max") and len(node.args) < 1 or node.func.id == "round" and len(node.args) not in (1, 2):
                raise ExprError(f"{node.func.id} needs its arguments in {expr!r}")
    return tree


@lru_cache(maxsize=1 << 17)  # deriving the design intent asks the same few hundred formulas for their names half a million times
def _names(expr: str) -> frozenset[str]:
    tree = parse(expr)
    calls = {n.func.id for n in ast.walk(tree) if isinstance(n, ast.Call)}
    return frozenset({n.id for n in ast.walk(tree) if isinstance(n, ast.Name)} - calls - set(CONSTS))


def names_in(expr: str) -> set[str]:
    return set(_names(expr))  # a set of its own: callers may add to it


_GLOBALS = {"__builtins__": {}, **FUNCS, **CONSTS}


@lru_cache(maxsize=1 << 17)
def _compiled(expr: str):
    """The checked expression as Python bytecode: parse() admits only numbers, names, + - * / ** and FUNCS, so eval
    sees nothing else. ~10x faster than walking the tree — regenerating a 12k-line sheet evaluates every formula."""
    return compile(parse(expr), "<formula>", "eval")


def evaluate(expr: str | ast.Expression, scope: dict[str, float]) -> float:
    if isinstance(expr, str):
        try:
            v = float(eval(_compiled(expr), _GLOBALS, scope))  # parse() admitted arithmetic on names only
        except ExprError:
            raise
        except NameError as exc:
            raise ExprError(f"unknown name {exc.name}") from exc
        except ZeroDivisionError as exc:
            raise ExprError("division by zero") from exc
        except (ValueError, OverflowError) as exc:  # sqrt of a negative, asin beyond ±1, an overflowing power …
            raise ExprError(f"{exc} in {expr!r}") from exc
        except TypeError as exc:  # a complex result (a negative to a fractional power)
            raise ExprError(f"not a real number in {expr!r}: {exc}") from exc
        if not math.isfinite(v):
            raise ExprError(f"{expr!r} is not a finite number ({v})")
        return v
    tree = expr

    def ev(n):
        if isinstance(n, ast.Expression):
            return ev(n.body)
        if isinstance(n, ast.Constant):
            return float(n.value)
        if isinstance(n, ast.Name):
            if n.id in scope:
                return scope[n.id]
            if n.id in CONSTS:
                return CONSTS[n.id]
            raise ExprError(f"unknown name {n.id}")
        if isinstance(n, ast.UnaryOp):
            v = ev(n.operand)
            if isinstance(n.op, ast.Not):
                return float(not v)
            return -v if isinstance(n.op, ast.USub) else v
        if isinstance(n, ast.Compare):
            left = ev(n.left)
            for op, right_node in zip(n.ops, n.comparators, strict=False):
                right = ev(right_node)
                ok = {ast.Lt: left < right, ast.LtE: left <= right, ast.Gt: left > right, ast.GtE: left >= right,
                      ast.Eq: left == right, ast.NotEq: left != right}[type(op)]
                if not ok:
                    return 0.0
                left = right
            return 1.0
        if isinstance(n, ast.IfExp):
            return ev(n.body) if ev(n.test) else ev(n.orelse)
        if isinstance(n, ast.BoolOp):
            vals = [ev(v) for v in n.values]
            return float(all(vals)) if isinstance(n.op, ast.And) else float(any(vals))
        if isinstance(n, ast.BinOp):
            a, b = ev(n.left), ev(n.right)
            if isinstance(n.op, ast.Add):
                return a + b
            if isinstance(n.op, ast.Sub):
                return a - b
            if isinstance(n.op, ast.Mult):
                return a * b
            if isinstance(n.op, ast.Div):
                if b == 0:
                    raise ExprError("division by zero")
                return a / b
            if isinstance(n.op, ast.Pow):
                return a**b
        if isinstance(n, ast.Call):
            try:
                return float(FUNCS[n.func.id](*[ev(a) for a in n.args]))
            except (ValueError, OverflowError, TypeError) as exc:
                raise ExprError(f"{n.func.id}: {exc}") from exc
        raise ExprError("bad expression")

    v = ev(tree)
    if not math.isfinite(v):
        raise ExprError(f"not a finite number ({v})")
    return v


# ── kinds of quantity ────────────────────────────────────────────────────────────

LENGTH, ANGLE, RATIO, ANY = "length", "angle", "ratio", "any"
_DIM_OF_UNIT = {"mm": LENGTH, "m": LENGTH, "deg": ANGLE, "°": ANGLE, "rad": RATIO, "-": RATIO, "": RATIO}


def dim_of_unit(unit: str | None) -> str:
    return _DIM_OF_UNIT.get((unit or "").strip(), RATIO)


def check_dims(expr: str, dims: dict[str, str], want: str | None = None) -> str:
    """The kind of quantity `expr` is (length, angle, ratio; a bare number fits any), from the kinds of its names —
    or ExprError naming the step that mixes kinds: a length plus an angle, a sine of a length, sind of a ratio given in
    radians, a set-out line that is not a length. `want`: the kind the result must be."""
    tree = parse(expr)

    def same(a: str, b: str, what: str) -> str:
        if a == ANY:
            return b
        if b == ANY or a == b:
            return a
        art = {ANGLE: "an angle", LENGTH: "a length", RATIO: "a ratio"}
        raise ExprError(f"{what} mixes {art.get(a, a)} with {art.get(b, b)} in {expr!r}")

    def ev(n) -> tuple[str, int]:  # (kind, power of length) — area / volume when a length is multiplied by a length
        if isinstance(n, ast.Expression):
            return ev(n.body)
        if isinstance(n, ast.Constant):
            return ANY, 0
        if isinstance(n, ast.Name):
            if n.id in CONSTS:
                return ANY, 0
            k = dims.get(n.id, LENGTH)
            return k, 1 if k == LENGTH else 0
        if isinstance(n, ast.UnaryOp):
            return (RATIO, 0) if isinstance(n.op, ast.Not) else ev(n.operand)
        if isinstance(n, ast.BinOp):
            a, b = ev(n.left), ev(n.right)
            if isinstance(n.op, (ast.Add, ast.Sub)):
                kind = same(a[0], b[0], "+/−")
                if a[0] != ANY and b[0] != ANY and a[1] != b[1]:
                    raise ExprError(f"adding a length to an area (unlike powers of length) in {expr!r}")
                return kind, max(a[1], b[1])
            if isinstance(n.op, ast.Mult):
                if ANGLE in (a[0], b[0]) and ANY not in (a[0], b[0]) and RATIO not in (a[0], b[0]):
                    raise ExprError(f"an angle multiplied by a {b[0] if a[0] == ANGLE else a[0]} in {expr!r}")
                p = a[1] + b[1]
                kind = ANGLE if ANGLE in (a[0], b[0]) else LENGTH if p != 0 else (RATIO if RATIO in (a[0], b[0]) or LENGTH in (a[0], b[0]) else ANY)
                return kind, p
            if isinstance(n.op, ast.Div):
                p = a[1] - b[1]
                if a[0] == ANGLE and b[0] in (ANY, RATIO):
                    return ANGLE, 0
                if ANGLE in (a[0], b[0]) and not (a[0] == ANGLE and b[0] == ANGLE):
                    raise ExprError(f"dividing an angle and a {b[0] if a[0] == ANGLE else a[0]} in {expr!r}")
                return (LENGTH if p != 0 else (ANY if a[0] == b[0] == ANY else RATIO)), p
            if isinstance(n.op, ast.Pow):
                if b[0] not in (ANY, RATIO) or not isinstance(n.right, ast.Constant):
                    if a[1] != 0:
                        raise ExprError(f"a length to a non-constant power in {expr!r}")
                    return (ANY if a[0] == ANY else RATIO), 0
                k = float(n.right.value)
                p = a[1] * k
                if abs(p - round(p)) > 1e-9:
                    raise ExprError(f"a fractional power of a length in {expr!r}")
                return (LENGTH if round(p) != 0 else a[0] if a[0] in (ANY, RATIO) else RATIO), round(p)
        if isinstance(n, ast.Call):
            f = n.func.id
            args = [ev(x) for x in n.args]
            if f in ("sind", "cosd", "tand"):
                if args[0][0] not in (ANGLE, ANY):
                    raise ExprError(f"{f} takes an angle in degrees, not a {args[0][0]}, in {expr!r}")
                return RATIO, 0
            if f in ("sin", "cos", "tan"):
                if args[0][0] == ANGLE:
                    raise ExprError(f"{f} takes radians: use {f}d for an angle in degrees, in {expr!r}")
                if args[0][1] != 0:
                    raise ExprError(f"{f} of a length in {expr!r}")
                return RATIO, 0
            if f in ("asind", "acosd", "atand", "asin", "acos", "atan"):
                if args[0][1] != 0 or args[0][0] == ANGLE:
                    raise ExprError(f"{f} takes a ratio, not a {args[0][0]}, in {expr!r}")
                return (ANGLE if f.endswith("d") else RATIO), 0
            if f in ("atan2d", "atan2"):
                same(args[0][0], args[1][0], f)
                return (ANGLE if f == "atan2d" else RATIO), 0
            if f == "deg":
                return ANGLE, 0
            if f == "rad":
                if args[0][0] not in (ANGLE, ANY):
                    raise ExprError(f"rad converts degrees, not a {args[0][0]}, in {expr!r}")
                return RATIO, 0
            if f == "sqrt":
                if args[0][1] % 2:
                    raise ExprError(f"the square root of an odd power of a length in {expr!r}")
                return (LENGTH if args[0][1] else args[0][0] if args[0][0] != ANGLE else RATIO), args[0][1] // 2
            if f in ("min", "max", "abs", "round", "floor", "ceil", "clamp", "hypot"):
                k = args[0][0]
                for x in args[1:] if f != "round" else []:  # round's second argument is a count of decimals
                    k = same(k, x[0], f)
                return k, args[0][1]
            if f == "sign":
                return RATIO, 0
            if f in ("dot", "cross"):
                k = args[0][0]
                for x in args[1:]:
                    k = same(k, x[0], f)
                return k, 2 * args[0][1]
            if f in ("rotx", "roty"):
                k = args[0][0]
                for x in args[1:4]:
                    k = same(k, x[0], f)
                if args[4][0] not in (ANGLE, ANY):
                    raise ExprError(f"{f}'s angle is in degrees, not a {args[4][0]}, in {expr!r}")
                return k, args[0][1]
        if isinstance(n, (ast.Compare, ast.BoolOp)):
            vals = [n.left, *n.comparators] if isinstance(n, ast.Compare) else n.values
            kinds = [ev(v) for v in vals]
            if isinstance(n, ast.Compare):
                k = kinds[0][0]
                for x in kinds[1:]:
                    k = same(k, x[0], "a comparison")
            return RATIO, 0
        if isinstance(n, ast.IfExp):
            ev(n.test)
            a, b = ev(n.body), ev(n.orelse)
            return same(a[0], b[0], "the two branches"), max(a[1], b[1])
        return ANY, 0

    kind, power = ev(tree)
    if want and kind not in (want, ANY):
        art = {ANGLE: "an angle", LENGTH: "a length", RATIO: "a ratio"}
        raise ExprError(f"{expr!r} is {art.get(kind, kind)}, not {art.get(want, want)}")
    if want == LENGTH and kind == LENGTH and power != 1:
        raise ExprError(f"{expr!r} is a length to the power {power} (an area or worse), not a length")
    return kind


