"""The parametric program — the UPCE shape, in plain data:

    PARAMETERS   named values a person types (Width = 3000 mm, GroundLevel = 96.100 m)
        ↓
    FORMULAS     every set-out line (datum) as an expression of parameters and other datums
                 ("x7 = x3 + Width"), plus named derived values ("TotalWidth = …")
        ↓
    BINDINGS     every entity point = its datum + a fixed offset (from the analysis)
        ↓
    GEOMETRY     regenerated by evaluating the formulas in dependency order

All lengths in formulas are millimetres; levels are metres (a level line's formula is
"FormationLevel * 1000"). Expressions are a small safe language: numbers, names,
+ − × ÷, parentheses, min/max/abs/sqrt/round. No Python is ever executed.
"""

from __future__ import annotations

import ast
import json
import math
import re
from dataclasses import asdict, dataclass, field
from functools import lru_cache

from .ir import Analysis, GapKind, Model

NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
FUNCS = {"min": min, "max": max, "abs": abs, "sqrt": math.sqrt, "round": round}


class ExprError(ValueError):
    pass


@lru_cache(maxsize=1 << 17)  # a big sheet re-evaluates ~10k formulas per regeneration; the trees are never mutated
def parse(expr: str) -> ast.Expression:
    try:
        tree = ast.parse(expr.replace("^", "**"), mode="eval")
    except SyntaxError as exc:
        raise ExprError(f"not an expression: {expr!r}") from exc
    for node in ast.walk(tree):
        ok = isinstance(node, (ast.Expression, ast.BinOp, ast.UnaryOp, ast.Constant, ast.Name, ast.Load, ast.Call,
                               ast.Add, ast.Sub, ast.Mult, ast.Div, ast.Pow, ast.USub, ast.UAdd))
        if not ok:
            raise ExprError(f"{type(node).__name__} is not allowed in {expr!r}")
        if isinstance(node, ast.Constant) and not isinstance(node.value, (int, float)):
            raise ExprError(f"only numbers are allowed as constants in {expr!r}")
        if isinstance(node, ast.Call) and not (isinstance(node.func, ast.Name) and node.func.id in FUNCS):
            raise ExprError(f"unknown function in {expr!r}")
    return tree


def names_in(expr: str) -> set[str]:
    tree = parse(expr)
    calls = {n.func.id for n in ast.walk(tree) if isinstance(n, ast.Call)}
    return {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)} - calls


_GLOBALS = {"__builtins__": {}, **FUNCS}


@lru_cache(maxsize=1 << 17)
def _compiled(expr: str):
    """The checked expression as Python bytecode: parse() admits only numbers, names, + - * / ** and FUNCS, so eval
    sees nothing else. ~10x faster than walking the tree — regenerating a 12k-line sheet evaluates every formula."""
    return compile(parse(expr), "<formula>", "eval")


def evaluate(expr: str | ast.Expression, scope: dict[str, float]) -> float:
    if isinstance(expr, str):
        try:
            return float(eval(_compiled(expr), _GLOBALS, scope))  # parse() admitted arithmetic on names only
        except NameError as exc:
            raise ExprError(f"unknown name {exc.name}") from exc
        except ZeroDivisionError as exc:
            raise ExprError("division by zero") from exc
    tree = expr

    def ev(n):
        if isinstance(n, ast.Expression):
            return ev(n.body)
        if isinstance(n, ast.Constant):
            return float(n.value)
        if isinstance(n, ast.Name):
            if n.id not in scope:
                raise ExprError(f"unknown name {n.id}")
            return scope[n.id]
        if isinstance(n, ast.UnaryOp):
            v = ev(n.operand)
            return -v if isinstance(n.op, ast.USub) else v
        if isinstance(n, ast.BinOp):
            a, b = ev(n.left), ev(n.right)
            if isinstance(n.op, ast.Add):
                return a + b
            if isinstance(n.op, ast.Sub):
                return a - b
            if isinstance(n.op, ast.Mult):
                return a * b
            if isinstance(n.op, ast.Div):
                if b == 0:
                    raise ExprError("division by zero")
                return a / b
            if isinstance(n.op, ast.Pow):
                return a**b
        if isinstance(n, ast.Call):
            return FUNCS[n.func.id](*[ev(a) for a in n.args])
        raise ExprError("bad expression")

    return ev(tree)


@dataclass
class Param:
    name: str
    label: str
    value: float  # mm for lengths, m for levels
    unit: str = "mm"  # mm | m | -
    kind: str = "length"  # length | level | count | ratio
    component: str = ""
    source: str = "geometry"  # geometry | dimension | ai | person
    measures: tuple[str, str] | None = None  # the two datums it is the distance between
    confidence: float = 0.0
    evidence: list[str] = field(default_factory=list)
    occurrences: int = 1
    note: str = ""


@dataclass
class Component:
    name: str
    type: str
    description: str = ""
    loops: list[str] = field(default_factory=list)  # entity ids (closed outlines, open lines) that belong to it
    datums: list[str] = field(default_factory=list)
    regions: list[str] = field(default_factory=list)  # closed regions (topology) it is made of
    level: str = "component"  # assembly | component | subcomponent
    parent: str | None = None
    existing: bool = False
    parametrize: bool = True  # the AI's recommendation
    held: bool = False  # kept as drawn (a person's selection, or existing work held fixed)
    confidence: float | None = None
    evidence: list[str] = field(default_factory=list)


@dataclass
class Relation:
    name: str
    expr: str  # in parameters (mm / m)
    label: str = ""
    check: str | None = None  # the geometry it states, as a datum expression ("x11 - x1")
    enforced: bool = False  # true when the model keeps it under every edit
    dimensioned: bool = False


@dataclass
class Program:
    analysis: Analysis
    params: dict[str, Param]
    formulas: dict[str, str]  # datum id → expression (mm)
    origin: dict[str, str]  # datum id → "geometry" | "ai"
    radius: dict[int, str] = field(default_factory=dict)  # circle item → radius expression (mm)
    relations: list[Relation] = field(default_factory=list)
    components: list[Component] = field(default_factory=list)
    structure: dict = field(default_factory=dict)  # type, family, views, summary, questions
    text_links: dict[int, list[tuple[str, str, int]]] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)
    # Design intent, as checked: line roles, behaviours and constraints with their status, the measured
    # impact of each parameter on each part, the selection applied, items for a person to review.
    intent: dict = field(default_factory=dict)
    _order: list[str] | None = None

    # ── evaluation ───────────────────────────────────────────────────────────────

    def defaults(self) -> dict[str, float]:
        return {p.name: p.value for p in self.params.values()}

    def order(self) -> list[str]:
        """Datums in dependency order; raises on a cycle (naming it)."""
        if self._order is not None:
            return self._order
        deps = {d: sorted(n for n in names_in(e) if n in self.formulas) for d, e in self.formulas.items()}
        out: list[str] = []
        state: dict[str, int] = {}
        for root in self.formulas:  # depth first without recursion: a big sheet chains thousands of lines
            if state.get(root, 0) == 2:
                continue
            stack = [(root, iter(deps[root]))]
            state[root] = 1
            while stack:
                d, it = stack[-1]
                nxt = next(it, None)
                if nxt is None:
                    stack.pop()
                    state[d] = 2
                    out.append(d)
                    continue
                s_ = state.get(nxt, 0)
                if s_ == 2:
                    continue
                if s_ == 1:
                    path = [x for x, _ in stack]
                    cyc = path[path.index(nxt):] + [nxt]
                    raise ExprError("cycle: " + " → ".join(cyc))
                state[nxt] = 1
                stack.append((nxt, iter(deps[nxt])))
        self._order = out
        return out

    def invalidate(self) -> None:
        self._order = None

    def datum_values(self, values: dict[str, float] | None = None) -> dict[str, float]:
        """Every datum in DRAWING units."""
        scope = self.defaults()
        if values:
            scope.update(values)
        u = self.analysis.drawing.units_mm
        out_mm: dict[str, float] = {}
        for d in self.order():  # one scope filled in dependency order (copying it per line was quadratic on big sheets)
            out_mm[d] = scope[d] = evaluate(self.formulas[d], scope)
        return {d: v / u for d, v in out_mm.items()}

    def change_plan(self) -> tuple[dict[str, int], dict[str, list[str]], dict[str, float]]:
        """For many one-value changes in a row (the ±10 % checks): each line's place in the order, the lines that
        use each name, and every line at the defaults (mm). Built once; valid while the formulas do not change."""
        order = self.order()
        users: dict[str, list[str]] = {}
        for d in order:
            for n in names_in(self.formulas[d]):
                users.setdefault(n, []).append(d)
        u = self.analysis.drawing.units_mm
        return {d: i for i, d in enumerate(order)}, users, {d: v * u for d, v in self.datum_values().items()}

    def datum_values_changed(self, values: dict[str, float], plan) -> dict[str, float]:
        """datum_values(values), recomputing only the lines downstream of the values that changed."""
        pos, users, base_mm = plan
        scope = self.defaults()
        changed = [k for k, v in values.items() if scope.get(k) != v]
        scope.update(values)
        scope.update(base_mm)
        todo, seen = list(changed), set()
        while todo:
            for d in users.get(todo.pop(), ()):
                if d not in seen:
                    seen.add(d)
                    todo.append(d)
        out_mm = dict(base_mm)
        for d in sorted(seen, key=pos.__getitem__):
            out_mm[d] = scope[d] = evaluate(self.formulas[d], scope)
        u = self.analysis.drawing.units_mm
        return {d: v / u for d, v in out_mm.items()}

    def radii(self, values: dict[str, float] | None = None) -> dict[int, float]:
        scope = self.defaults()
        if values:
            scope.update(values)
        u = self.analysis.drawing.units_mm
        return {i: evaluate(e, scope) / u for i, e in self.radius.items()}

    def relation_value(self, r: Relation, values: dict[str, float] | None = None) -> float:
        """Over parameters, or — for a quantity worked out by the set-out (a named size between lines other inputs fix) —
        over set-out lines, measured on the regenerated drawing."""
        scope = self.defaults()
        if values:
            scope.update(values)
        if names_in(r.expr) - scope.keys():
            return self.measured(r.expr, values)
        return evaluate(r.expr, scope)

    def measured(self, expr: str, values: dict[str, float] | None = None) -> float:
        """A datum expression ("x11 - x1") on the regenerated datums, in mm."""
        u = self.analysis.drawing.units_mm
        dv = {d: v * u for d, v in self.datum_values(values).items()}
        return evaluate(expr, dv)

    # ── serialisation ────────────────────────────────────────────────────────────

    def to_json(self) -> dict:
        an = self.analysis
        u = an.drawing.units_mm
        return {
            "format": "dxf-autoparam/program-1",
            "source": an.drawing.path,
            "units": "mm (levels in m)",
            "structure": self.structure,
            "components": [asdict(c) for c in self.components],
            "parameters": [asdict(p) for p in self.params.values()],
            "datums": {d: {"axis": an.datums[d].axis, "value_mm": an.datums[d].value * u, "formula": self.formulas[d],
                           "origin": self.origin.get(d, "geometry")} for d in self.formulas},
            "radius": {str(k): v for k, v in self.radius.items()},
            "relations": [asdict(r) for r in self.relations],
            "intent": {k: v for k, v in self.intent.items() if k != "parts"},
            "bindings": [{"item": i, "pt": k, "axis": ax, "datum": d, "offset_mm": off * u}
                         for (i, k, ax), (d, off) in an.slot_datum.items()],
            "notes": self.notes,
        }

    def save(self, path: str) -> None:
        with open(path, "w") as f:
            json.dump(self.to_json(), f, indent=1, default=str)


# ── from the deterministic model ─────────────────────────────────────────────────


def _num(v: float) -> str:
    r = round(v, 6)
    if r == int(r):
        return str(int(r))
    return f"{round(v, 9):.9f}".rstrip("0").rstrip(".")


def _plus(expr: str, c: float) -> str:
    if abs(c) < 1e-6:
        return expr
    return f"{expr} + {_num(c)}" if c > 0 else f"{expr} - {_num(-c)}"


def from_model(model: Model) -> Program:
    """The geometric baseline as a program: every datum written relative to the one it is set out from."""
    an = model.analysis
    u = an.drawing.units_mm
    datums = an.datums
    params: dict[str, Param] = {}
    for p in model.parameters.values():
        level = p.kind in ("level", "position")
        cid = next((c.id for c in an.clusters.values() if c.name == p.name), None)
        measures = None
        if cid:
            g0 = an.gaps.get(an.clusters[cid].gaps[0])
            if g0 is not None and g0.axis in ("x", "y"):
                measures = (g0.a, g0.b)
        params[p.name] = Param(
            name=p.name, label=p.label, value=p.value if level else p.value * u, unit="m" if p.kind == "level" else "mm",
            kind="level" if p.kind == "level" else "length", source="geometry", measures=measures, confidence=p.confidence,
            evidence=[f"{e.kind}: {e.detail}" for e in p.evidence], occurrences=p.occurrences,
        )
    scope = {p.name: p.value for p in params.values()}
    # which pinned datum carries which level
    pinned = {d: next(iter(f.terms)) for d, f in model.forms.items()
              if len(f.terms) == 1 and model.parameters.get(next(iter(f.terms))) is not None
              and model.parameters[next(iter(f.terms))].kind in ("level", "position")}
    formulas: dict[str, str] = {}
    off = an.level_offset_mm
    for d, name in pinned.items():
        if model.parameters[name].kind == "level":
            formulas[d] = f"{name} * 1000" + (f" - {_num(off)}" if off > 0 else f" + {_num(-off)}" if off < 0 else "")
        else:
            formulas[d] = name
    gaps = an.gaps
    for e in model.tree:
        if e.child in formulas:
            continue
        g = gaps.get(e.gap) if e.gap else None
        if e.how == "slope" and g is not None and g.slope:
            x1, y1, x2, y2, ratio = g.slope
            k = ratio if (e.parent, e.child) == (x1, x2) else -ratio
            body = f"{e.parent} + {_num(k)} * ({y2} - {y1})"
        elif e.how in ("gap", "symmetric") and e.param and e.param in params:
            k = e.sign * e.amount
            body = f"{e.parent} {'+' if k > 0 else '-'} {'' if abs(abs(k) - 1) < 1e-12 else _num(abs(k)) + ' * '}{e.param}"
        else:
            body = e.parent
        formulas[e.child] = body
    for root in model.roots.values():
        formulas.setdefault(root, _num(datums[root].value * u))
    for d in datums:
        formulas.setdefault(d, _num(datums[d].value * u))
    prog = Program(analysis=an, params=params, formulas=formulas, origin={d: "geometry" for d in formulas}, text_links=model.text_links)
    # Exactness: each datum reproduces where it was drawn (a residual stays a constant).
    scope = dict(scope)  # filled in dependency order (one scope, not a copy per line)
    for d in prog.order():
        v = evaluate(prog.formulas[d], scope)
        c = datums[d].value * u - v
        if abs(c) > 1e-6:
            prog.formulas[d] = _plus(prog.formulas[d], c)
        scope[d] = datums[d].value * u
    prog.invalidate()
    # A linear form in drawing units → millimetres: a length term keeps its coefficient
    # (both sides scale by the unit), a level term (metres) gains the unit, the constant too.
    def mm_expr(f) -> str:
        parts = []
        for p, c in sorted(f.terms.items(), key=lambda t: -abs(t[1])):
            level = model.parameters.get(p) is not None and model.parameters[p].kind in ("level", "position")
            cc = c * u if level else c
            parts.append(p if abs(cc - 1) < 1e-9 else f"{_num(cc)} * {p}")
        expr = " + ".join(parts)
        return (_plus(expr, f.const * u) if expr else _num(f.const * u)).replace("+ -", "- ")

    for item, f in model.radius.items():
        prog.radius[item] = mm_expr(f)
    for r in model.results:
        g = gaps[r.gap]
        prog.relations.append(Relation(name=f"R_{g.id}", expr=mm_expr(r.form), label=r.label, check=f"{g.b} - {g.a}",
                                       enforced=True, dimensioned=r.dimensioned))
    return prog


def kind_of(an: Analysis, cid: str) -> GapKind:
    return an.clusters[cid].kind
