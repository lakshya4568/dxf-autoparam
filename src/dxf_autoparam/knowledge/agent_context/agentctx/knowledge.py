"""Knowledge index: a token index over knowledge and source records, and the compact global context index.

The token index is only a finder. It returns record ids; the records themselves carry the trust labels.
No embedding model and no LLM are used.
"""

from __future__ import annotations

import re
from collections import Counter, defaultdict
from typing import Any, Iterable

TOKEN = re.compile(r"[a-z0-9]+")
STOP = frozenset({"the", "a", "an", "of", "and", "or", "to", "in", "on", "for", "by", "is", "as", "at", "with", "from",
                  "be", "that", "this", "it", "are", "was", "not"})


def tokens(text: str | None) -> list[str]:
    if not text:
        return []
    return [t for t in TOKEN.findall(text.lower()) if len(t) > 1 and t not in STOP]


def build_token_index(records: Iterable[dict[str, Any]]) -> dict[str, list[str]]:
    index: dict[str, set[str]] = defaultdict(set)
    for record in records:
        text = " ".join(str(x) for x in (
            record.get("id"), record.get("kb_id"), record.get("title"), " ".join(record.get("aliases") or []),
            record.get("search_text"), record.get("summary"), record.get("kind"), record.get("topic"),
        ) if x)
        for token in set(tokens(text)):
            index[token].add(record["id"])
    return {token: sorted(ids) for token, ids in sorted(index.items())}


def rank(query: str, records_by_id: dict[str, dict[str, Any]], index: dict[str, list[str]],
         candidates: Iterable[str] | None = None) -> list[tuple[float, str]]:
    """Score records by how many query tokens they contain. Title and id matches count more."""
    terms = tokens(query)
    if not terms:
        return []
    scores: Counter[str] = Counter()
    for term in set(terms):
        for record_id in index.get(term, []):
            scores[record_id] += 1.0
    for record_id in list(scores):
        record = records_by_id.get(record_id, {})
        title = (record.get("title") or "").lower()
        ident = (record.get("kb_id") or record.get("id") or "").lower()
        for term in set(terms):
            if term in title:
                scores[record_id] += 0.5
            if term in ident:
                scores[record_id] += 0.25
    allowed = set(candidates) if candidates is not None else None
    ranked = [(score / len(set(terms)), rid) for rid, score in scores.items() if allowed is None or rid in allowed]
    ranked.sort(key=lambda pair: (-pair[0], pair[1]))
    return ranked


def global_index_markdown(
    *,
    knowledge: list[dict[str, Any]],
    sources: list[dict[str, Any]],
    observations_count: int,
    issues: list[dict[str, Any]],
) -> str:
    """Compact map of what exists, with retrieval locations. Written for an agent to read first."""
    by_cat = Counter(r["category"] for r in knowledge)
    by_src = Counter(s["kind"] for s in sources)
    issue_kinds = Counter(i["kind"] for i in issues)
    lines: list[str] = [
        "# Global context index (generated by agentctx; do not edit)",
        "",
        "A map, not the content. Every line names the record id to fetch with `ctx.py evidence <id>` "
        "or `ctx.py search <words>`.",
        "",
        "## Categories (kept apart on purpose)",
        "",
        "| Cat | Meaning | Knowledge records |",
        "|---|---|---|",
    ]
    from .policy import CATEGORY_NAMES

    for cat in ("A", "B", "C", "D", "E"):
        lines.append(f"| {cat} | {CATEGORY_NAMES[cat]} | {by_cat.get(cat, 0)} |")
    lines += [
        "",
        f"Observations (category A, stored per item in registry/observations.jsonl): {observations_count}.",
        "",
        "## Source kinds in the registry",
        "",
        "| Kind | Records |",
        "|---|---|",
    ]
    lines += [f"| {kind} | {count} |" for kind, count in sorted(by_src.items())]
    lines += ["", "## Drawing families (dataset, main corpus)", ""]
    fam = Counter(s.get("family") for s in sources if s.get("kind") == "drawing_sheet")
    grounded = Counter(s.get("family") for s in sources if s.get("kind") == "drawing_sheet"
                       and (s.get("completeness") or {}).get("grounding") == "filed")
    lines += ["| Family folder | Sheets | Grounded sheets |", "|---|---|---|"]
    lines += [f"| {name} | {count} | {grounded.get(name, 0)} |" for name, count in sorted(fam.items(), key=lambda kv: str(kv[0]))]
    lines += ["", "## Component classes with grounding ids (from the knowledge base)", ""]
    comp = sorted(
        (r for r in knowledge if r["topic"] == "component" and r.get("kb_id") and r.get("proposal_status") == "none"),
        key=lambda r: r["kb_id"],
    )
    for record in comp[:200]:
        cls = (record.get("raw") or {}).get("grounding", {}) or {}
        lines.append(f"- `{record['id']}` {record['title']} (class `{cls.get('class', '-')}`, {record['category']})")
    lines += ["", "## Rules and formulas (not executable; conditions in the record)", ""]
    for topic in ("rule", "formula", "level_chain", "constant", "conflict"):
        group = [r for r in knowledge if r["topic"] == topic]
        disputed = sum(1 for r in group if (r.get("trust") or {}).get("evidence_status") == "DISPUTED")
        lines.append(f"- {topic}: {len(group)} records, {disputed} disputed")
    lines += ["", "## Open issues by kind", ""]
    lines += [f"- {kind}: {count}" for kind, count in sorted(issue_kinds.items())]
    lines += [
        "",
        "## Where things are",
        "",
        "- `agent-context/registry/sources.jsonl`: every source record (sheets, grounding, RDSO, vector, books, instructions).",
        "- `agent-context/registry/observations.jsonl`: observations (A) with raw text, candidate reading and eligibility.",
        "- `agent-context/registry/issues.jsonl`: every known problem, with the purposes it affects.",
        "- `agent-context/knowledge/knowledge.jsonl`: knowledge records (B, C, D, E) with their trust labels.",
        "- `agent-context/reports/`: build report, issues, coverage.",
        "",
    ]
    return "\n".join(lines) + "\n"
