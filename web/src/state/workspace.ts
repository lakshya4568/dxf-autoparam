export type LeftTab = "views" | "layers" | "values" | "fidelity";
export type RightTab = "inspect" | "validate";

export interface Preview {
  changes: Record<string, number>;
  ents: Set<number>;
  prims: Prim[];
  errors: string[];
  warnings: string[];
  ok: boolean;
  failures: Failure[];
}

/** A refusal in one sentence: what kind of refusal the first failed check is, and the check itself. */
export function refusalLine(res: { errors?: string[]; error?: string; failures?: Failure[] }): string {
  const f = res.failures?.[0];
  if (f) return `${f.says}${f.existing ? " (it already failed before this change)" : ""} — ${f.message}`;
  return (res.errors ?? [])[0] ?? res.error ?? "";
}

